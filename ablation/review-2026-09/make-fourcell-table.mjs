#!/usr/bin/env node
// Generates the paper's four-cell results table from primary data only:
// unsealed rows from results/E1-fourcell-batch-metric.csv (the original
// four-cell reps, measured mechanically), sealed rows from each sealed rep's
// review-metrics.json. Nothing is typed by hand, so the table cannot drift
// from the logs. Unfinished sealed reps are counted as pending, not dropped.
//
// Usage: node make-fourcell-table.mjs > fourcell-table.tex
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const rows = [];

// Unsealed: with-/without- x weak/strong. Leakage-driven completions are the
// reps whose held-out touch count is nonzero AND that reached 12/12.
const csv = readFileSync(join(here, 'results', 'E1-fourcell-batch-metric.csv'), 'utf-8').trim().split('\n');
const head = csv[0].split(',');
const unsealed = csv.slice(1).map((l) => Object.fromEntries(l.split(',').map((v, i) => [head[i], v])));
for (const tier of ['weak', 'strong']) {
  for (const cond of ['with', 'without']) {
    // The four-cell design's strong cells are reps 1-3; with-rep-strong4/5 are
    // the later catchandtrade replication reps (different settings config),
    // so they are excluded here and reported with that replication instead.
    const reps = unsealed.filter((r) => r.rep.startsWith(cond + '-rep') && (tier === 'strong') === r.rep.includes('strong')
      && !(tier === 'strong' && Number(r.rep.match(/(\d+)$/)[1]) > 3));
    const full = reps.filter((r) => r.heldOut === '12/12');
    rows.push({
      protocol: 'unsealed', tier, cond: cond === 'with' ? 'blocking' : 'log-only',
      n: reps.length, pending: 0,
      clean: full.filter((r) => Number(r.touch) === 0).length,
      leaked: full.filter((r) => Number(r.touch) > 0).length,
      batch: reps.filter((r) => Number(r.maxInOne) >= 3).length,
      maxBatch: Math.max(0, ...reps.map((r) => Number(r.maxInOne))),
      blocks: 0
    });
  }
}

// Sealed: arm A = blocking, B = log-only (C/D are E3/E4a, reported separately).
const sealedRoots = [['weak', join(homedir(), 'sealed-runs', 'review-2026-09')], ['strong', join(homedir(), 'sealed-runs', 'review-2026-09-strong')]];
for (const [tier, root] of sealedRoots) {
  const stateRoot = join(root, '.claude-plugin-state');
  if (!existsSync(stateRoot)) continue;
  for (const [arm, cond] of [['A', 'blocking'], ['B', 'log-only']]) {
    const names = readdirSync(stateRoot).filter((r) => r.startsWith(arm + '-rep'));
    const done = names.map((r) => join(stateRoot, r, 'review-metrics.json')).filter(existsSync).map((p) => JSON.parse(readFileSync(p, 'utf-8')));
    const valid = done.filter((m) => !m.degenerate);
    rows.push({
      protocol: 'sealed', tier, cond,
      n: valid.length, pending: names.length - done.length,
      clean: valid.filter((m) => m.heldOutFullCompletion && m.outOfTreeAccessAttempts === 0).length,
      leaked: valid.filter((m) => m.heldOutFullCompletion && m.outOfTreeAccessAttempts > 0).length,
      batch: valid.filter((m) => m.maxNewFilesInOneInterval >= 3).length,
      maxBatch: Math.max(0, ...valid.map((m) => m.maxNewFilesInOneInterval)),
      blocks: valid.reduce((s, m) => s + (m.untestedContractBlocked || 0) + (m.specEditsBlocked || 0), 0)
    });
  }
}

const tierName = { weak: 'Haiku', strong: 'Sonnet' };
const lines = rows.map((r) =>
  `${r.protocol} & ${tierName[r.tier]} & ${r.cond} & ${r.n}${r.pending ? ` (+${r.pending} pending)` : ''} & ${r.clean} & ${r.leaked} & ${r.batch} (max ${r.maxBatch}) & ${r.blocks} \\\\`);
console.log(`% Generated by ablation/review-2026-09/make-fourcell-table.mjs at ${new Date().toISOString()} — do not edit by hand.
\\begin{tabular}{lllrrrrr}
\\toprule
Held-out & Tier & Hooks & Valid reps & 12/12 clean & 12/12 via leak & Reps batch-building ($\\geq$3 new files) & Blocks \\\\
\\midrule
${lines.join('\n')}
\\bottomrule
\\end{tabular}`);
